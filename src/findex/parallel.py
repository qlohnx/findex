"""Disk-backed map/reduce indexing for text files and streamed XML pages.

The staging files are private, temporary pickle streams created by this module.
Only paths are submitted to workers. Partial results retain document texts for
search snippets, so those texts are serialized on the way back to the parent.
"""

import multiprocessing
import pickle
import time
from collections.abc import Iterable, Iterator
from concurrent.futures import ProcessPoolExecutor, ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path
from typing import Literal, cast

from findex.index import InvertedIndex
from findex.tokenize import tokenize

type ExecutorName = Literal["serial", "threads", "processes"]
type StagedDocument = tuple[int, str, str, str]


@dataclass(slots=True)
class PartialIndex:
    """A chunk's compact postings and metadata, not its raw token stream."""

    index: InvertedIndex
    cpu_seconds: float


@dataclass(slots=True)
class BuildTiming:
    wall_seconds: float = 0.0
    merge_seconds: float = 0.0
    parent_cpu_seconds: float = 0.0
    worker_cpu_seconds: float = 0.0


class WorkerBuildError(RuntimeError):
    """Keep the original worker exception and remote traceback as the cause."""


def _worker_results(results: Iterable[PartialIndex]) -> Iterator[PartialIndex]:
    try:
        yield from results
    except Exception as exc:
        raise WorkerBuildError("index worker failed") from exc


def stage_pages(
    pages: Iterable[tuple[str, str]],
    source: str,
    directory: Path,
    chunk_size: int = 256,
) -> list[Path]:
    """Stream pages into bounded-size files, assigning global IDs in input order."""
    if chunk_size < 1:
        raise ValueError("chunk_size must be positive")
    directory.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []
    stream = None
    try:
        for ordinal, (title, text) in enumerate(pages):
            if ordinal % chunk_size == 0:
                if stream is not None:
                    stream.close()
                path = directory / f"chunk-{len(paths):06d}.pkl"
                paths.append(path)
                stream = path.open("wb")
            doc_id = ordinal + 1
            assert stream is not None
            pickle.dump((doc_id, f"{source}#{doc_id}", title, text), stream)
    finally:
        if stream is not None:
            stream.close()
    return paths


def _documents(paths: list[Path]) -> Iterator[StagedDocument]:
    for path in paths:
        with path.open("rb") as stream:
            while True:
                try:
                    # These files are generated by stage_pages, never user-supplied.
                    yield cast(StagedDocument, pickle.load(stream))
                except EOFError:
                    break


def build_partial(doc_paths: list[Path], positions: bool = False) -> PartialIndex:
    """Build one picklable partial index from paths to staged document chunks."""
    start_cpu = time.process_time()
    index = InvertedIndex(positions=positions)
    for doc_id, path, title, text in _documents(doc_paths):
        index.add_document(doc_id, path, list(tokenize(text)), title=title, text=text)
    return PartialIndex(index=index, cpu_seconds=time.process_time() - start_cpu)


def _build_chunk(task: tuple[Path, bool]) -> PartialIndex:
    path, positions = task
    return build_partial([path], positions=positions)


def merge(
    partials: Iterable[PartialIndex],
    positions: bool = False,
    timing: BuildTiming | None = None,
) -> InvertedIndex:
    """Merge ordered, disjoint ID ranges while preserving Lab 04 serialization."""
    result = InvertedIndex(positions=positions)
    last_doc_id = 0
    for partial in partials:
        start = time.perf_counter()
        part = partial.index
        if part.positions != positions:
            raise ValueError("partial index positions mode differs")
        ids = list(part.doc_meta)
        if ids and ids[0] <= last_doc_id:
            raise ValueError("partial document IDs must increase")
        if ids:
            last_doc_id = ids[-1]
        result.doc_meta.update(part.doc_meta)
        result.doc_lengths.update(part.doc_lengths)
        result.doc_texts.update(part.doc_texts)
        for term, postings in part.index.items():
            result.index[term].extend(postings)
        if timing is not None:
            timing.merge_seconds += time.perf_counter() - start
            timing.worker_cpu_seconds += partial.cpu_seconds
    return result


def build_from_chunks(
    paths: list[Path],
    *,
    positions: bool = False,
    executor: ExecutorName = "serial",
    workers: int = 1,
) -> tuple[InvertedIndex, BuildTiming]:
    """Run the same map/reduce work serially, with threads, or with processes."""
    if workers < 1:
        raise ValueError("workers must be positive")
    if executor not in ("serial", "threads", "processes"):
        raise ValueError(f"unknown executor: {executor}")
    start_wall = time.perf_counter()
    start_cpu = time.process_time()
    timing = BuildTiming()
    if executor == "serial":
        result = merge([build_partial(paths, positions=positions)], positions, timing)
    elif executor == "threads":
        with ThreadPoolExecutor(max_workers=workers) as pool:
            tasks = ((path, positions) for path in paths)
            result = merge(
                _worker_results(pool.map(_build_chunk, tasks)), positions, timing
            )
    else:
        with ProcessPoolExecutor(
            max_workers=workers, mp_context=multiprocessing.get_context("spawn")
        ) as pool:
            tasks = ((path, positions) for path in paths)
            result = merge(
                _worker_results(pool.map(_build_chunk, tasks)), positions, timing
            )
    timing.wall_seconds = time.perf_counter() - start_wall
    timing.parent_cpu_seconds = time.process_time() - start_cpu
    return result, timing
